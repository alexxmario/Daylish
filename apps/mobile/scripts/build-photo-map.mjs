/**
 * Inlines the dish photographs into a TypeScript module of `require()` calls.
 *
 *   npm run photos:map -w @daylish/mobile
 *
 * Metro resolves assets at build time from string literals, so
 * `require(`../../assets/dish-photos/${key}.webp`)` does not work — the bundler
 * has no way to know which files to include. The map has to be written out.
 *
 * Keyed on the dish title with only the *size* suffix removed. Diet variants
 * keep their own photograph deliberately: a vegan shakshuka has neither feta nor
 * eggs in it, and `identifyDish`'s `dishKey` — which strips `, vegan` too —
 * would have pointed it at a picture of the omnivore version.
 */
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const appRoot = join(here, '..');
const photoDir = join(appRoot, 'assets', 'dish-photos');
const outFile = join(appRoot, 'src', 'data', 'dish-photos.generated.ts');

const keys = readdirSync(photoDir)
  .filter((f) => f.endsWith('.webp'))
  .map((f) => f.replace(/\.webp$/, ''))
  .sort();

if (keys.length === 0) {
  console.error(`No .webp files in ${photoDir}. Run the pipeline's compress-images step first.`);
  process.exit(1);
}

// Cross-check against the library so a missing photograph is a build failure
// rather than a blank card someone notices in review.
const seedPath = join(appRoot, '..', '..', 'supabase', 'seed', 'recipes.json');
const recipes = JSON.parse(readFileSync(seedPath, 'utf8'));
const photoKey = (title) =>
  title
    .replace(/,\s*(light|hearty)$/i, '')
    .toLowerCase()
    .normalize('NFD')
    .replace(/[̀-ͯ]/g, '')
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-|-$/g, '');

const have = new Set(keys);
const missing = [...new Set(recipes.map((r) => photoKey(r.title)))].filter((k) => !have.has(k));
if (missing.length > 0) {
  console.error(`${missing.length} dishes have no photograph:`);
  for (const k of missing.slice(0, 10)) console.error(`  ${k}`);
  process.exit(1);
}

const body = keys
  .map((k) => `  '${k}': require('../../assets/dish-photos/${k}.webp'),`)
  .join('\n');

writeFileSync(
  outFile,
  `/**
 * Generated by scripts/build-photo-map.mjs — do not edit.
 *
 * ${keys.length} dish photographs. Keyed on the title with the size suffix
 * removed, so light and hearty share the dish's photograph while diet variants
 * keep their own.
 */

/** A \`require\`d image asset, as Metro represents it. */
export type PhotoAsset = number;

export const DISH_PHOTOS: Readonly<Record<string, PhotoAsset>> = {
${body}
};
`,
);

console.log(`Wrote ${keys.length} photo requires → src/data/dish-photos.generated.ts`);
