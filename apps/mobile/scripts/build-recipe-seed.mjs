/**
 * Inlines the validated recipe library into a TypeScript module.
 *
 * The same problem `packages/db/scripts/build-migrations.mjs` solves for SQL,
 * for the same reason: the bundle needs the data as JavaScript. Importing the
 * `.json` directly looks tidier and works under Metro, but Node's ESM loader
 * requires an `import ... with { type: 'json' }` attribute that Babel then has
 * to be taught about — so the runtime smoke test, which imports the real
 * repository, breaks. A generated `.ts` module works everywhere with no special
 * syntax on either side.
 *
 * Run after every `npm run pipeline -- --import`:
 *   npm run seed:recipes -w @daylish/mobile
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const source = join(here, '..', '..', '..', 'supabase', 'seed', 'recipes.json');
const outFile = join(here, '..', 'src', 'data', 'seed-recipes.generated.ts');

const recipes = JSON.parse(readFileSync(source, 'utf8'));

if (!Array.isArray(recipes) || recipes.length === 0) {
  console.error(`No recipes in ${source}. Run the pipeline import first.`);
  process.exit(1);
}

// Only the fields the app reads. `fdcId` and `matchedDescription` are dropped —
// they are the pipeline's audit trail, they roughly double the payload, and
// nothing on the device shows them.
const slim = recipes.map((recipe) => ({
  title: recipe.title,
  summary: recipe.summary,
  cuisine: recipe.cuisine,
  mealSlots: recipe.mealSlots,
  servings: recipe.servings,
  prepMinutes: recipe.prepMinutes,
  cookMinutes: recipe.cookMinutes,
  difficulty: recipe.difficulty,
  equipment: recipe.equipment,
  dietStyles: recipe.dietStyles,
  allergens: recipe.allergens,
  prepScore: recipe.prepScore,
  storageNotes: recipe.storageNotes,
  fridgeDays: recipe.fridgeDays,
  freezerMonths: recipe.freezerMonths,
  nutrientsPerServing: recipe.nutrientsPerServing,
  ingredients: recipe.ingredients.map((i) => ({
    name: i.name,
    grams: i.grams,
    displayQuantity: i.displayQuantity,
    preparation: i.preparation ?? null,
    optional: Boolean(i.optional),
  })),
  steps: recipe.steps.map((s) => ({
    order: s.order,
    instruction: s.instruction,
    durationMinutes: s.durationMinutes ?? null,
    isPassive: Boolean(s.isPassive),
  })),
}));

const banner = `/**
 * Generated by scripts/build-recipe-seed.mjs — do not edit.
 *
 * Source: supabase/seed/recipes.json, itself the output of
 * \`npm run pipeline -- --import recipes/\`, where every ingredient was resolved
 * against USDA FoodData Central and the nutrition computed from those matches.
 *
 * ${slim.length} recipes.
 */

import type { SeedRecipe } from './recipes.ts';

export const SEED_RECIPES: readonly SeedRecipe[] = `;

writeFileSync(outFile, `${banner}${JSON.stringify(slim, null, 2)} as const;\n`);

/**
 * The count, on its own, in a module small enough to load at boot.
 *
 * `seedRecipes` compares this against the row count in SQLite and returns early
 * when they match, which is every launch after the first. Reading `.length` off
 * the array itself would mean evaluating all ${slim.length} objects to learn one
 * number — so the number lives apart from the data it describes, and the array
 * is only imported on the launch that actually copies it in.
 */
const metaFile = join(here, '..', 'src', 'data', 'seed-recipes-count.generated.ts');
writeFileSync(
  metaFile,
  `/**
 * Generated by scripts/build-recipe-seed.mjs — do not edit.
 *
 * How many recipes \`seed-recipes.generated.ts\` holds. Kept separate so the
 * boot path can check whether seeding is needed without evaluating ${slim.length}
 * recipe objects to find out.
 */

export const SEED_RECIPE_COUNT = ${slim.length};
`,
);

const bytes = Buffer.byteLength(readFileSync(outFile));
console.log(`Wrote ${slim.length} recipes → ${outFile} (${Math.round(bytes / 1024)} KB)`);
console.log(`Wrote SEED_RECIPE_COUNT = ${slim.length} → ${metaFile}`);
